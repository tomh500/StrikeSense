const palette& get_palette()
{
    return k_palettes[std::clamp(g_uiThemePreset, 0, preset_count - 1)];
}

int get_preset()
{
    return std::clamp(g_uiThemePreset, 0, preset_count - 1);
}

void set_preset(int preset_id)
{
    const int clamped = std::clamp(preset_id, 0, preset_count - 1);
    if (g_uiThemePreset == clamped) return;
    g_uiThemePreset = clamped;
    std::wcout << L"[界面主题] 已切换到主题: " << get_preset_name(clamped) << std::endl;
}

const wchar_t* get_preset_name(int preset_id)
{
    const int clamped = std::clamp(preset_id, 0, preset_count - 1);
    return k_names[clamped];
}

bool is_advanced_preset(int preset_id)
{
    return std::clamp(preset_id, 0, preset_count - 1) >= preset_default_plus;
}

